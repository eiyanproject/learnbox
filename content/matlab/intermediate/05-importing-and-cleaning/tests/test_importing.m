lbx_run({
  'readtable_reads_every_row',   @() lbx_eq(6, height(readtable('readings.csv')))
  'readtable_finds_the_columns', @() lbx_eq(4, width(readtable('readings.csv')))
  'numeric_column_is_numeric',   @() lbx_true(isnumeric(readtable('readings.csv').Reading))
  'text_column_stays_text',      @() lbx_true(iscellstr(readtable('readings.csv').Station))
  'the_gap_became_nan',          @() lbx_true(isnan(readtable('readings.csv').Reading(2)))
  'missing_count_finds_the_gap', @() lbx_eq(1, missing_count(readtable('readings.csv')))
  'missing_count_of_clean_data', @() lbx_eq(0, missing_count(load_clean('readings.csv')))
  'load_clean_drops_the_row',    @() lbx_eq(5, height(load_clean('readings.csv')))
  'load_clean_keeps_the_rest',   @() lbx_eq(4, width(load_clean('readings.csv')))
  'load_clean_keeps_good_rows',  @() lbx_near(12.5, load_clean('readings.csv').Reading(1))
  'average_by_one_row_per_group',@() lbx_eq(2, height(average_by(load_clean('readings.csv'), 'Station', 'Reading')))
  'average_by_carries_a_count',  @() lbx_true(any(strcmp('GroupCount', average_by(load_clean('readings.csv'), 'Station', 'Reading').Properties.VariableNames)))
  'average_by_names_the_mean',   @() lbx_true(any(strcmp('mean_Reading', average_by(load_clean('readings.csv'), 'Station', 'Reading').Properties.VariableNames)))
  'average_by_computes_it',      @() lbx_near(13.5, north_mean())
  'average_by_counts_the_rows',  @() lbx_eq(2, north_count())
  'average_by_is_a_table',       @() lbx_type('table', average_by(load_clean('readings.csv'), 'Station', 'Reading'))
  'grouping_by_quality_too',     @() lbx_eq(2, height(average_by(load_clean('readings.csv'), 'Quality', 'Reading')))
});
