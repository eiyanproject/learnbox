lbx_run({
  'count_type_counts_doubles',  @() lbx_eq(2, count_type({1, 'a', 2}, 'double'))
  'count_type_counts_char',     @() lbx_eq(1, count_type({1, 'a', 2}, 'char'))
  'count_type_finds_none',      @() lbx_eq(0, count_type({1, 2}, 'char'))
  'count_type_of_empty',        @() lbx_eq(0, count_type({}, 'double'))
  'count_type_sees_a_cell',     @() lbx_eq(1, count_type({1, {2}}, 'cell'))
  'longest_finds_it',           @() lbx_str_eq('abc', longest({'a', 'abc', 'ab'}))
  'longest_ties_go_to_first',   @() lbx_str_eq('ab', longest({'ab', 'cd'}))
  'longest_ignores_non_text',   @() lbx_str_eq('ab', longest({1, 'ab', [1 2 3 4]}))
  'longest_of_nothing',         @() lbx_str_eq('', longest({}))
  'longest_of_no_text',         @() lbx_str_eq('', longest({1, 2}))
  'make_record_has_the_fields', @() lbx_eq({'name'; 'age'}, fieldnames(make_record('ada', 36)))
  'make_record_keeps_values',   @() lbx_str_eq('ada', getfield(make_record('ada', 36), 'name'))
  'make_record_keeps_the_age',  @() lbx_eq(36, getfield(make_record('ada', 36), 'age'))
  'field_or_reads_a_field',     @() lbx_eq(36, field_or(make_record('ada', 36), 'age', 0))
  'field_or_falls_back',        @() lbx_eq(-1, field_or(make_record('ada', 36), 'height', -1))
  'field_or_default_can_be_text', @() lbx_str_eq('none', field_or(make_record('ada', 36), 'city', 'none'))
  'braces_reach_the_contents',  @() lbx_true(ischar(contents_of({'hi'})))
  'parens_keep_the_cell',       @() lbx_true(iscell(slice_of({'hi', 'there'})))
});
