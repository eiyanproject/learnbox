lbx_run({
  'to_sizes_is_categorical',     @() lbx_type('categorical', to_sizes({'small'}))
  'to_sizes_keeps_the_order',    @() lbx_eq({'small'; 'medium'; 'large'}, categories(to_sizes({'small'})))
  'to_sizes_is_ordinal',         @() lbx_true(isordinal(to_sizes({'small'})))
  'unused_categories_survive',   @() lbx_eq(3, numel(categories(to_sizes({'small'}))))
  'countcats_counts_zero_too',   @() lbx_eq([2 0 1], countcats(to_sizes({'small','large','small'})))
  'outside_the_set_is_undefined',@() lbx_true(isundefined(to_sizes({'enormous'})))
  'ordinal_comparison_works',    @() lbx_true(to_sizes({'large'}) > to_sizes({'small'}))
  'order_is_not_alphabetical',   @() lbx_false(to_sizes({'medium'}) > to_sizes({'large'}))
  'at_least_includes_the_ref',   @() lbx_eq(logical([1 1 0]), at_least(to_sizes({'large','medium','small'}), 'medium'))
  'at_least_the_smallest',       @() lbx_eq(3, sum(at_least(to_sizes({'large','medium','small'}), 'small')))
  'at_least_the_largest',        @() lbx_eq(1, sum(at_least(to_sizes({'large','medium','small'}), 'large')))
  'most_common_finds_it',        @() lbx_str_eq('red', most_common({'red','blue','red'}))
  'most_common_ties_alphabetical', @() lbx_str_eq('blue', most_common({'red','blue'}))
  'most_common_of_one',          @() lbx_str_eq('solo', most_common({'solo'}))
  'most_common_all_the_same',    @() lbx_str_eq('x', most_common({'x','x','x'}))
  'most_common_returns_char',    @() lbx_true(ischar(most_common({'a','a','b'})))
  'most_common_of_empty_throws', @() lbx_error('most_common:empty', @() most_common({}))
  'unordered_refuses_comparison',@() lbx_error('categorical:notOrdinal', @() categorical({'a','b'})(1) < categorical({'a','b'})(2))
});
