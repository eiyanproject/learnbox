lbx_run({
  'parse_dates_reads_iso',       @() lbx_eq(2, length(parse_dates({'2026-01-01', '2026-03-01'})))
  'parse_dates_keeps_the_year',  @() lbx_eq(2026, year(parse_dates({'2026-01-01'})))
  'parse_dates_keeps_month_day', @() lbx_eq([3 1], [month(parse_dates({'2026-03-01'})) day(parse_dates({'2026-03-01'}))])
  'parse_dates_gives_datetimes', @() lbx_type('datetime', parse_dates({'2026-01-01'}))
  'parse_dates_rejects_rubbish', @() lbx_error('parse_dates:bad', @() parse_dates({'not a date'}))
  'elapsed_days_counts',         @() lbx_near(59, elapsed_days(datetime(2026,1,1), datetime(2026,3,1)))
  'elapsed_days_of_nothing',     @() lbx_near(0, elapsed_days(datetime(2026,1,1), datetime(2026,1,1)))
  'elapsed_days_can_be_negative',@() lbx_near(-1, elapsed_days(datetime(2026,1,2), datetime(2026,1,1)))
  'elapsed_days_is_a_number',    @() lbx_true(isnumeric(elapsed_days(datetime(2026,1,1), datetime(2026,1,2))))
  'a_difference_is_a_duration',  @() lbx_type('duration', datetime(2026,1,2) - datetime(2026,1,1))
  'adding_days_moves_the_date',  @() lbx_eq(8, day(datetime(2026,1,1) + days(7)))
  'adding_a_number_is_refused',  @() lbx_error('datetime:badOperand', @() datetime(2026,1,1) + 7)
  'in_window_is_inclusive',      @() lbx_eq(logical([1 1 1]), in_window(three_dates(), datetime(2026,1,1), datetime(2026,1,3)))
  'in_window_excludes_outside',  @() lbx_eq(logical([0 1 0]), in_window(three_dates(), datetime(2026,1,2), datetime(2026,1,2)))
  'in_window_can_match_nothing', @() lbx_eq(0, sum(in_window(three_dates(), datetime(2027,1,1), datetime(2027,1,2))))
  'latest_finds_the_last',       @() lbx_eq(3, day(latest(three_dates())))
  'latest_of_one',               @() lbx_eq(1, day(latest(datetime(2026,1,1))))
  'latest_ignores_order',        @() lbx_eq(3, day(latest(parse_dates({'2026-01-03','2026-01-01'}))))
  'latest_of_empty_throws',      @() lbx_error('latest:empty', @() latest(parse_dates({})))
});
